#!/usr/bin/env python3
"""CLI to seed the product catalog: MongoDB only.

Usage:
    python seed.py [--count N] [--reset]

Seeding targets the MongoDB backend directly, using the same knobs as the
app: ``MONGO_URI`` (see ``DEFAULT_MONGO_URI``) and ``MONGO_DB`` (see
``DEFAULT_MONGO_DB``). In-memory seeding is pointless: the data dies with the
seeding process, and the in-memory backend exists only as the behavioral
reference for the repository contract (see ``repository.py``).

The dataset is generated with a FIXED RNG seed (42). All content fields are
deterministic; ids are generated by the repository, and ``created_at`` is
spread over the last 90 days from the wall-clock ``now`` (second granularity),
so it is NOT identical across runs. Inserts go through ``create_products`` in
batches of 500.

This tool does raw bulk inserts and does NOT call ``ensure_indexes``: index
creation belongs to the application, which calls it once at startup.
"""

from __future__ import annotations

import argparse
import contextlib
import os
import random
import time
from datetime import datetime, timedelta

from pymongo import MongoClient
from pymongo.errors import PyMongoError

from models import Brand, Category, Product, now_utc
from mongo_repository import PRODUCT_COLLECTION_NAME, MongoProductRepository
from repository import DEFAULT_MONGO_DB, DEFAULT_MONGO_URI

DEFAULT_COUNT = 50000
# Suggested minimum dataset size (informational only, not enforced).
SUGGESTED_MIN_COUNT = 20000
BATCH_SIZE = 500
RNG_SEED = 42
PING_TIMEOUT_MS = 2500

